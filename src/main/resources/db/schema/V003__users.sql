CREATE TABLE shop.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    role VARCHAR(16) NOT NULL,
    active BOOLEAN NOT NULL,
    CONSTRAINT app_users_email_unique UNIQUE (email),
    CONSTRAINT app_users_name_not_blank CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT app_users_email_canonical CHECK (email = lower(btrim(email)) AND position('@' IN email) > 1),
    CONSTRAINT app_users_password_bcrypt CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    CONSTRAINT app_users_role_valid CHECK (role IN ('ADMIN', 'CUSTOMER'))
);
