BEGIN;

CREATE TABLE shop.purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES shop.app_users(id),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    total NUMERIC(38,2) NOT NULL,
    CONSTRAINT orders_total_positive CHECK (total > 0),
    CONSTRAINT orders_status_valid CHECK (
        (status = 'CREATED' AND cancelled_at IS NULL) OR
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND cancelled_at >= created_at))
);
CREATE INDEX orders_customer_id_idx ON shop.purchase_orders(customer_id, id);
CREATE INDEX orders_created_at_idx ON shop.purchase_orders(created_at);

CREATE TABLE shop.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES shop.purchase_orders(id),
    product_id BIGINT NOT NULL REFERENCES shop.products(id),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(19,2) NOT NULL,
    subtotal NUMERIC(38,2) NOT NULL,
    CONSTRAINT order_items_product_unique UNIQUE (order_id, product_id),
    CONSTRAINT order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT order_items_price_positive CHECK (unit_price > 0),
    CONSTRAINT order_items_subtotal_valid CHECK (subtotal = unit_price * quantity)
);
CREATE INDEX order_items_product_id_idx ON shop.order_items(product_id);

COMMIT;
